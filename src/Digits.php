<?php

declare(strict_types=1);

/**
 * Цифры почтового индекса: каждая цифра — набор из 9 палочек шаблона.
 *
 *    ①            точки шаблона:  A───B
 *  ┌────┐                         │ ╱ │
 * ②│  ④╱│③                        C───D
 *  │ ╱  │                         │ ╱ │
 *  ├─⑤──┤                         E───F
 * ⑥│  ⑧╱│⑦
 *  │ ╱  │
 *  └────┘
 *    ⑨
 */
final class Digits
{
    /** Палочка => [номер, описание, точка-начало, точка-конец]; точки в координатах шаблона 1×2 */
    public const SEGMENTS = [
        1 => ['name' => 'верх',                'from' => [0, 0], 'to' => [1, 0]],
        2 => ['name' => 'левая верхняя',       'from' => [0, 0], 'to' => [0, 1]],
        3 => ['name' => 'правая верхняя',      'from' => [1, 0], 'to' => [1, 1]],
        4 => ['name' => 'верхняя диагональ',   'from' => [1, 0], 'to' => [0, 1]],
        5 => ['name' => 'середина',            'from' => [0, 1], 'to' => [1, 1]],
        6 => ['name' => 'левая нижняя',        'from' => [0, 1], 'to' => [0, 2]],
        7 => ['name' => 'правая нижняя',       'from' => [1, 1], 'to' => [1, 2]],
        8 => ['name' => 'нижняя диагональ',    'from' => [1, 1], 'to' => [0, 2]],
        9 => ['name' => 'низ',                 'from' => [0, 2], 'to' => [1, 2]],
    ];

    /** Какие палочки горят у каждой цифры */
    public const DIGITS = [
        0 => [1, 2, 3, 6, 7, 9],
        1 => [4, 3, 7],
        2 => [1, 3, 8, 9],
        3 => [1, 4, 5, 7, 9],
        4 => [2, 5, 3, 7],
        5 => [1, 2, 5, 7, 9],
        6 => [4, 5, 6, 7, 9],
        7 => [1, 4, 6],
        8 => [1, 2, 3, 5, 6, 7, 9],
        9 => [1, 2, 3, 5, 8],
    ];

    /** Цифра -> массив из 9 нулей/единиц: [палочка1, палочка2, ..., палочка9] */
    public static function toInput(int $digit): array
    {
        $x = [];
        for ($s = 1; $s <= count(self::SEGMENTS); $s++) {
            $x[] = in_array($s, self::DIGITS[$digit], true) ? 1 : 0;
        }
        return $x;
    }

    /**
     * Что реально подаётся в сеть: палочка есть → +1, нет → −1.
     * С нулём "пустая" палочка ничего не вносила бы в сумму w·x, и сеть видела бы
     * только горящие палочки; с −1 отсутствие палочки — тоже информация.
     */
    public static function encode(array $segments): array
    {
        $x = [];
        foreach ($segments as $s) {
            $x[] = $s ? 1.0 : -1.0;
        }
        return $x;
    }

    /** Желаемый выход сети: +1 у нейрона правильной цифры, −1 у остальных (под диапазон tanh) */
    public static function target(int $digit): array
    {
        $y = [];
        for ($d = 0; $d < 10; $d++) {
            $y[] = $d === $digit ? 1.0 : -1.0;
        }
        return $y;
    }

    /** Если набор палочек в точности совпадает с цифрой — вернуть её, иначе null */
    public static function match(array $x): ?int
    {
        for ($d = 0; $d < 10; $d++) {
            if (self::toInput($d) === array_map('intval', $x)) {
                return $d;
            }
        }
        return null;
    }
}
